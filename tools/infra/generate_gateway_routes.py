#!/usr/bin/env python3
"""Generate the finite Nginx gateway route and marker maps from business OpenAPI."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
OPENAPI = ROOT / "docs/api/openapi.yaml"
OUTPUT = ROOT / "tools/deploy/nginx/route-map.conf"
METHODS = ("get", "post", "put", "patch", "delete")
TEMPLATE_PART = re.compile(r"(\{[A-Za-z_][A-Za-z0-9_]*\})")
VALID_PATH = re.compile(r"/[A-Za-z0-9/_{}-]+\Z")


def business_routes(document: dict[str, Any]) -> list[tuple[str, str]]:
    routes: set[tuple[str, str]] = set()
    paths = document.get("paths")
    if not isinstance(paths, dict):
        raise ValueError("OpenAPI paths must be an object")
    for path, path_item in paths.items():
        if not isinstance(path, str) or not VALID_PATH.fullmatch(path):
            raise ValueError(f"unsupported OpenAPI path template: {path!r}")
        if path.startswith("/health/"):
            continue
        if not isinstance(path_item, dict):
            raise ValueError(f"OpenAPI path item must be an object: {path}")
        for method in METHODS:
            if method in path_item:
                routes.add((method.upper(), path))
    if not routes:
        raise ValueError("OpenAPI contains no business operations")
    return sorted(routes)


def route_regex(path: str) -> str:
    parts = TEMPLATE_PART.split(path)
    return "".join("[^/?]+" if TEMPLATE_PART.fullmatch(part) else re.escape(part) for part in parts)


def map_block(
    source: str,
    target: str,
    rows: list[tuple[str, str]],
    default: str = "__unmatched__",
) -> str:
    lines = [f'map "{source}" {target} {{', f'    default "{default}";']
    lines.extend(f'    "{key}" "{value}";' for key, value in rows)
    lines.append("}")
    return "\n".join(lines)


def render(routes: list[tuple[str, str]]) -> str:
    route_rows = [
        (f"~^{method}:{route_regex(path)}(?:/)?(?:\\?.*)?$", path)
        for method, path in routes
    ]
    location_rows = [
        (
            f"~^{method}:(?:https?://[^/]+)?{route_regex(path)}(?:\\?.*)?$",
            path,
        )
        for method, path in routes
    ]
    unique_paths = sorted({path for _, path in routes})
    marker_rows = [(f"{path}:{path}", "1") for path in unique_paths]
    terminal_rows = [
        (f"~^{method}:{route_regex(path)}/(?:\\?.*)?$", "1")
        for method, path in routes
    ]
    redirect_rows = [
        (f"{status}:{method}:{path}:{path}:api:1:1", "1")
        for method, path in routes
        for status in (307, 308)
    ]

    sections = [
        "# Generated by tools/infra/generate_gateway_routes.py; do not edit by hand.",
        "# Matches request URI only for finite route selection; raw values are never emitted.",
        map_block("$request_method:$request_uri", "$prl_route", route_rows),
        "",
        "# Redirect locations must resolve to the same published method/template.",
        map_block("$request_method:$upstream_http_location", "$prl_location_route", location_rows),
        "",
        map_block(
            "$prl_route:$upstream_http_x_prl_route",
            "$prl_route_marker_matches",
            marker_rows,
            default="0",
        ),
        "",
        "map $prl_route $prl_route_is_published {",
        '    default "0";',
        *[f'    "{path}" "1";' for path in unique_paths],
        "}",
        "",
        map_block(
            "$request_method:$request_uri",
            "$prl_terminal_slash",
            terminal_rows,
            default="0",
        ),
        "",
        (
            'map "$status:$request_method:$prl_route:$prl_location_route:'
            '$prl_upstream_identity:$prl_route_marker_matches:$prl_terminal_slash" '
            "$prl_canonical_redirect {"
        ),
        '    default "0";',
        *[f'    "{key}" "{value}";' for key, value in redirect_rows],
        "}",
    ]
    return "\n".join(sections) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    try:
        document = yaml.safe_load(OPENAPI.read_text(encoding="utf-8"))
        routes = business_routes(document)
        generated = render(routes)
    except (OSError, yaml.YAMLError, ValueError) as exc:
        print(f"gateway route generation failed: {exc}", file=sys.stderr)
        return 2

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(
                "gateway route map is stale; run tools/infra/generate_gateway_routes.py",
                file=sys.stderr,
            )
            return 1
        print(f"gateway route map verified: {len(routes)} business operations")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"generated gateway route map: {len(routes)} business operations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
